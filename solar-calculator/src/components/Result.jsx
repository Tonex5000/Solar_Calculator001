import { jsPDF } from 'jspdf';

const Result = ({ results, isLoading, error, onReset, formData }) => {
  
  const generatePDF = () => {
    const doc = new jsPDF();
    
    // Header
    doc.setFontSize(22);
    doc.setTextColor(102, 126, 234);
    doc.text('Solar System Quotation', 105, 25, { align: 'center' });
    
    doc.setDrawColor(102, 126, 234);
    doc.setLineWidth(0.5);
    doc.line(20, 30, 190, 30);
    
    // Date
    doc.setFontSize(10);
    doc.setTextColor(100, 100, 100);
    doc.text(`Date: ${new Date().toLocaleDateString()}`, 20, 40);
    
    // Section: System Requirements
    doc.setFontSize(14);
    doc.setTextColor(51, 51, 51);
    doc.text('System Requirements', 20, 55);
    
    doc.setFontSize(11);
    doc.setTextColor(80, 80, 80);
    
    const load = formData?.load || results?.load || 'N/A';
    const backupHours = formData?.backup_hours || 'N/A';
    const batteryType = formData?.battery_type || 'N/A';
    const switchingVolt = formData?.switching_volt || 'N/A';
    const chargingHours = formData?.charging_hours || 'N/A';
    const panelWattage = formData?.panel_wattage === 'other' 
      ? formData?.other_wattage 
      : formData?.panel_wattage || 'N/A';
    
    doc.text(`Total Load: ${load} W`, 25, 65);
    doc.text(`Backup Hours: ${backupHours} hours`, 25, 72);
    doc.text(`Battery Type: ${batteryType}`, 25, 79);
    doc.text(`Switching Volt: ${switchingVolt}V`, 25, 86);
    doc.text(`Charging Hours: ${chargingHours} hours`, 25, 93);
    doc.text(`Panel Wattage: ${panelWattage} W`, 25, 100);
    
    // Section: Recommended System
    doc.setFontSize(14);
    doc.setTextColor(51, 51, 51);
    doc.text('Recommended System Configuration', 20, 115);
    
    doc.setFontSize(12);
    doc.setTextColor(102, 126, 234);
    doc.text('⚡ Inverter Size', 25, 125);
    doc.setTextColor(80, 80, 80);
    doc.setFontSize(11);
    doc.text(`${results.inverter_kva} KVA`, 120, 125);
    
    doc.setTextColor(102, 126, 234);
    doc.setFontSize(12);
    doc.text('🔋 Battery Capacity', 25, 135);
    doc.setTextColor(80, 80, 80);
    doc.setFontSize(11);
    doc.text(`${results.battery_ah} Ah`, 120, 135);
    
    doc.setTextColor(102, 126, 234);
    doc.setFontSize(12);
    doc.text('☀️ Solar Watts', 25, 145);
    doc.setTextColor(80, 80, 80);
    doc.setFontSize(11);
    doc.text(`${results.solar_watts} W`, 120, 145);
    
    doc.setTextColor(102, 126, 234);
    doc.setFontSize(12);
    doc.text('📦 Number of Panels', 25, 155);
    doc.setTextColor(80, 80, 80);
    doc.setFontSize(11);
    doc.text(`${results.number_of_panels}`, 120, 155);
    
    doc.setTextColor(102, 126, 234);
    doc.setFontSize(12);
    doc.text('🔋 Battery Connection', 25, 165);
    doc.setTextColor(80, 80, 80);
    doc.setFontSize(11);
    doc.text(`${results.series_connection}S × ${results.parallel_connection}P`, 120, 165);
    
    doc.setTextColor(102, 126, 234);
    doc.setFontSize(12);
    doc.text('🔋 Total Batteries', 25, 175);
    doc.setTextColor(80, 80, 80);
    doc.setFontSize(11);
    doc.text(`${results.battery_count} (${results.battery_type})`, 120, 175);
    
    // Appliance Details Section
    const startY = results.battery_count ? 190 : 180;
    if (formData?.applianceDetails && formData.applianceDetails.length > 0) {
      doc.setFontSize(14);
      doc.setTextColor(51, 51, 51);
      doc.text('Appliance Load Breakdown', 20, startY);
      
      doc.setFontSize(10);
      doc.setTextColor(100, 100, 100);
      doc.text('Appliance', 25, startY + 10);
      doc.text('Watts', 90, startY + 10);
      doc.text('Qty', 115, startY + 10);
      doc.text('Mult', 135, startY + 10);
      doc.text('Load', 160, startY + 10);
      
      let yPos = startY + 18;
      doc.setTextColor(80, 80, 80);
      doc.setFontSize(10);
      
      formData.applianceDetails.forEach((app) => {
        doc.text(app.name.substring(0, 20), 25, yPos);
        doc.text(String(app.wattage), 90, yPos);
        doc.text(String(app.quantity), 115, yPos);
        doc.text(`×${app.multiplier}`, 135, yPos);
        doc.text(`${app.calculatedLoad} W`, 160, yPos);
        yPos += 7;
      });
    }
    
    // Footer
    doc.setDrawColor(200, 200, 200);
    doc.line(20, 270, 190, 270);
    doc.setFontSize(9);
    doc.setTextColor(150, 150, 150);
    doc.text('This quotation is generated by Solar Sizing Calculator', 105, 278, { align: 'center' });
    
    // Save PDF
    doc.save('Solar_System_Quotation.pdf');
  };

  if (isLoading) {
    return (
      <div className="step-content result-container">
        <div className="loading">
          <div className="spinner"></div>
          <p>Calculating your solar system...</p>
        </div>
      </div>
    );
  }

  if (error) {
    return (
      <div className="step-content result-container">
        <div className="error-message">
          <h3>Error</h3>
          <p>{error}</p>
          <button onClick={onReset} className="btn btn-primary">
            Try Again
          </button>
        </div>
      </div>
    );
  }

  if (!results) {
    return null;
  }

  return (
    <div className="step-content result-container">
      <h2>Your Solar System Results</h2>
      <p className="step-description">Based on your inputs, here's your recommended solar setup:</p>
      
      <div className="results-grid">
        <div className="result-card">
          <div className="result-icon">⚡</div>
          <div className="result-label">Inverter Size</div>
          <div className="result-value">{results.inverter_watts} <span>KVA</span></div>
          <div className="result-note">Required inverter capacity</div>
        </div>
        
        <div className="result-card">
          <div className="result-icon">🔋</div>
          <div className="result-label">Battery Capacity</div>
          <div className="result-value">{results.battery_ah} <span>Ah</span></div>
          <div className="result-note">Battery amp-hour rating</div>
        </div>
        
        <div className="result-card">
          <div className="result-icon">☀️</div>
          <div className="result-label">Solar Watts</div>
          <div className="result-value">{results.solar_watts} <span>W</span></div>
          <div className="result-note">Total solar panel wattage</div>
        </div>
        
        <div className="result-card">
          <div className="result-icon">📦</div>
          <div className="result-label">Number of Panels</div>
          <div className="result-value">{results.number_of_panels}</div>
          <div className="result-note">Panels needed</div>
        </div>

        <div className="result-card">
          <div className="result-icon">🔋</div>
          <div className="result-label">Battery Connection</div>
          <div className="result-value">{results.series_connection}S × {results.parallel_connection}P</div>
          <div className="result-note">Series × Parallel</div>
        </div>

        <div className="result-card">
          <div className="result-icon">🔋</div>
          <div className="result-label">Total Batteries</div>
          <div className="result-value">{results.battery_count}</div>
          <div className="result-note">{results.battery_type} batteries</div>
        </div>
      </div>

      <button onClick={generatePDF} className="btn btn-pdf">
        📄 Download Quotation (PDF)
      </button>

      <button onClick={onReset} className="btn btn-primary btn-reset">
        Start New Calculation
      </button>
    </div>
  );
};

export default Result;
